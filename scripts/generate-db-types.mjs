// Reproduce types from the committed migrations, including nullability and FKs.
// Production drift must be checked separately before deployment.
import { createDatabase } from "../tests/database.mjs";
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";
import { schemaContract } from "./schema-contract.mjs";
const db = await createDatabase();
try {
  const columns = (
    await db.query(`select c.table_name,c.column_name,c.udt_name,c.is_nullable,c.column_default,c.is_generated,t.table_type
 from information_schema.columns c join information_schema.tables t using(table_catalog,table_schema,table_name)
 where c.table_schema='public' order by c.table_name,c.ordinal_position`)
  ).rows;
  const keys = (
    await db.query(`select cl.relname as table_name, con.conname, rf.relname as referenced_relation,
 array(select attname from unnest(con.conkey) with ordinality as k(id,n) join pg_attribute a on a.attrelid=con.conrelid and a.attnum=k.id order by n) as columns,
 array(select attname from unnest(con.confkey) with ordinality as k(id,n) join pg_attribute a on a.attrelid=con.confrelid and a.attnum=k.id order by n) as referenced_columns
 from pg_constraint con join pg_class cl on cl.oid=con.conrelid join pg_class rf on rf.oid=con.confrelid join pg_namespace ns on ns.oid=cl.relnamespace
 where con.contype='f' and ns.nspname='public'`)
  ).rows;
  const type = (c) =>
    c.udt_name === "app_role"
      ? "AppRole"
      : ["int4", "int8", "numeric", "float8"].includes(c.udt_name)
        ? "number"
        : c.udt_name === "bool"
          ? "boolean"
          : c.udt_name === "jsonb"
            ? "Json"
            : "string";
  const tables = [...new Set(columns.map((c) => c.table_name))];
  const entry = (name) => {
    const cols = columns.filter((c) => c.table_name === name);
    const shape = (mode) =>
      "{\n" +
      cols
        .filter((c) => mode === "Row" || c.is_generated === "NEVER")
        .map(
          (c) =>
            `          ${c.column_name}${mode === "Update" || (mode === "Insert" && (c.is_nullable === "YES" || c.column_default !== null)) ? "?" : ""}: ${type(c)}${c.is_nullable === "YES" ? " | null" : ""}`,
        )
        .join("\n") +
      "\n        }";
    const relations = keys
      .filter((k) => k.table_name === name)
      .map(
        (k) =>
          `{foreignKeyName: ${JSON.stringify(k.conname)}; columns: ${JSON.stringify(k.columns)}; isOneToOne: false; referencedRelation: ${JSON.stringify(k.referenced_relation)}; referencedColumns: ${JSON.stringify(k.referenced_columns)}}`,
      )
      .join(",\n");
    return `      ${name}: {\n        Row: ${shape("Row")}\n        Insert: ${shape("Insert")}\n        Update: ${shape("Update")}\n        Relationships: [${relations}]\n      }`;
  };
  const output = await format(
    `// Generated by scripts/generate-db-types.mjs. Do not edit manually.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];
export type AppRole = 'admin' | 'sales' | 'operations' | 'safety' | 'management' | 'read_only';
export type Database = {
 __InternalSupabase: { PostgrestVersion: '14.5' };
 public: {
  Tables: {
${tables
  .filter((n) => columns.find((c) => c.table_name === n).table_type === "BASE TABLE")
  .map(entry)
  .join("\n")}
  };
  Views: {
${tables
  .filter((n) => columns.find((c) => c.table_name === n).table_type === "VIEW")
  .map(entry)
  .join("\n")}
  };
  Functions: {
    has_role: { Args: {_user_id:string;_role:AppRole}; Returns:boolean };
    has_any_role: { Args: {_user_id:string;_roles:AppRole[]}; Returns:boolean };
    can_access_table: { Args: {_table:string;_write?:boolean}; Returns:boolean };
    revise_rate: { Args: {_id:string;_expected_updated_at:string;_values:Json}; Returns:Database['public']['Tables']['rates']['Row'] };
  };
  Enums: { app_role: AppRole };
  CompositeTypes: { [_ in never]: never };
 }
};
export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];
export type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];
export type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update'];
export type Enums<T extends keyof Database['public']['Enums']> = Database['public']['Enums'][T];
`,
    { parser: "typescript", printWidth: 100 },
  );
  const path = "src/integrations/supabase/types.ts";
  if (process.argv.includes("--check")) {
    const generatedColumns = columns
      .filter((c) => c.is_generated !== "NEVER")
      .map((c) => `${c.table_name}.${c.column_name}`);
    const actual = schemaContract(await readFile(path, "utf8"), generatedColumns);
    const expected = schemaContract(output, generatedColumns);
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
      const differences = [];
      for (const table of new Set([...Object.keys(actual), ...Object.keys(expected)]))
        for (const mode of ["Row", "Insert", "Update"])
          for (const column of new Set([
            ...Object.keys(actual[table]?.[mode] ?? {}),
            ...Object.keys(expected[table]?.[mode] ?? {}),
          ]))
            if (
              JSON.stringify(actual[table]?.[mode]?.[column]) !==
              JSON.stringify(expected[table]?.[mode]?.[column])
            )
              differences.push(
                `${table}.${mode}.${column}: ${JSON.stringify(actual[table]?.[mode]?.[column])} expected ${JSON.stringify(expected[table]?.[mode]?.[column])}`,
              );
      throw new Error(
        `Database types differ from migrations. Run pnpm db:types.\n${differences.join("\n")}`,
      );
    }
  } else await writeFile(path, output);
} finally {
  await db.close();
}
